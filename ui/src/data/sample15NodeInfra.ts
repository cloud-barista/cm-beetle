// Helper to build standard network interfaces and routing for 10.0.1.0/24 nodes
function buildNodeNetwork(ipOctet: number, macSuffix: string) {
  const ip = `10.0.1.${ipOctet}`;
  return {
    interfaces: [
      {
        name: 'lo',
        state: 'up',
        mtu: 65536,
        ipv4CidrBlocks: ['127.0.0.1/8'],
        ipv6CidrBlocks: ['::1/128'],
      },
      {
        name: 'ens5',
        state: 'up',
        macAddress: `02:42:ac:11:01:${macSuffix}`,
        mtu: 9001,
        ipv4CidrBlocks: [`${ip}/24`],
        ipv6CidrBlocks: [`fe80::42:acff:fe11:${macSuffix}/64`],
      },
    ],
    routingTable: [
      {
        destination: '0.0.0.0/0',
        gateway: '10.0.1.1',
        interface: 'ens5',
        linkState: 'up',
        metric: 100,
        protocol: 'kernel',
        scope: 'universe',
      },
      {
        destination: '10.0.1.0/24',
        gateway: '10.0.1.1',
        interface: 'ens5',
        linkState: 'up',
        metric: 100,
        protocol: 'kernel',
        scope: 'universe',
      },
    ],
  };
}

// Helper to build standard inbound TCP firewall rules plus VPC traffic
function buildFirewallRules(inboundPorts: string[]) {
  return [
    ...inboundPorts.map((port) => ({
      action: 'allow',
      direction: 'inbound',
      dstCIDR: '0.0.0.0/0',
      dstPorts: port,
      protocol: 'tcp',
      srcCIDR: '0.0.0.0/0',
      srcPorts: '*',
    })),
    {
      action: 'allow',
      direction: 'inbound',
      dstCIDR: '0.0.0.0/0',
      dstPorts: '*',
      protocol: '*',
      srcCIDR: '10.0.0.0/16',
      srcPorts: '*',
    },
    {
      action: 'allow',
      direction: 'outbound',
      dstCIDR: '0.0.0.0/0',
      dstPorts: '*',
      protocol: '*',
      srcCIDR: '0.0.0.0/0',
      srcPorts: '*',
    },
  ];
}

